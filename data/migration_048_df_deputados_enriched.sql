DROP VIEW IF EXISTS v_cldf_perfil_completo CASCADE;
CREATE VIEW v_cldf_perfil_completo AS
SELECT
    d.id,
    d.nome_candidato,
    d.nome_civil,
    d.sigla_partido,
    d.sexo,
    d.cor_raca,
    d.estado_civil,
    d.grau_instrucao,
    d.ocupacao,
    d.data_nascimento,
    EXTRACT(YEAR FROM AGE(d.data_nascimento::DATE)) AS idade_atual,
    d.uf_nascimento,
    d.municipio_nascimento,
    d.nr_candidato,
    d.sq_candidato,
    d.votos_total,
    d.pct_votos,
    d.gasto_campanha_r1,
    d.total_bens,
    d.foto_url,
    d.coligacao,
    d.descricao_totaliz,
    d.situacao,
    d.mandato_inicio,
    d.mandato_fim,
    COALESCE(b.count_bens, 0) AS itens_patrimonio
FROM df_deputados_distritais_cldf d
LEFT JOIN (
    SELECT sq_candidato, COUNT(*) AS count_bens
    FROM df_deputados_distritais_bens
    GROUP BY sq_candidato
) b ON b.sq_candidato = d.sq_candidato
WHERE d.situacao = 'ELEITO'
ORDER BY d.votos_total DESC;

COMMENT ON VIEW v_cldf_perfil_completo IS
    'Perfil completo dos 24 deputados distritais eleitos — todos os campos disponíveis';

DROP VIEW IF EXISTS v_cldf_bancada_genero CASCADE;
CREATE VIEW v_cldf_bancada_genero AS
SELECT
    sigla_partido,
    COUNT(*) FILTER (WHERE sexo ILIKE '%MASC%') AS homens,
    COUNT(*) FILTER (WHERE sexo ILIKE '%FEM%') AS mulheres,
    COUNT(*) AS total
FROM df_deputados_distritais_cldf
WHERE situacao = 'ELEITO'
GROUP BY sigla_partido
ORDER BY total DESC;

COMMENT ON VIEW v_cldf_bancada_genero IS
    'Bancada CLDF por gênero e partido';

DROP VIEW IF EXISTS v_cldf_patrimonio CASCADE;
CREATE VIEW v_cldf_patrimonio AS
SELECT
    d.nome_candidato,
    d.sigla_partido,
    d.total_bens,
    d.gasto_campanha_r1,
    d.votos_total,
    CASE WHEN d.gasto_campanha_r1 > 0
         THEN ROUND(d.gasto_campanha_r1 / d.votos_total, 2)
         ELSE NULL
    END AS custo_por_voto
FROM df_deputados_distritais_cldf d
WHERE d.situacao = 'ELEITO'
ORDER BY d.total_bens DESC NULLS LAST;

COMMENT ON VIEW v_cldf_patrimonio IS
    'Patrimônio e gasto de campanha dos deputados distritais eleitos';

GRANT SELECT ON v_cldf_perfil_completo TO cognee;
GRANT SELECT ON v_cldf_bancada_genero TO cognee;
GRANT SELECT ON v_cldf_patrimonio TO cognee;

